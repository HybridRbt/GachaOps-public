"""Prepare an external OK-WW descriptor and verify drift. Does not launch main.py."""
import hashlib
import json
import os
import sys
from pathlib import Path

from .ok_inventory import inspect_installation
from .preflight import desktop_report
from .windows_observation import elevation_report, find_matching_processes


PYTHON_SETTINGS = {"PYTHONHOME", "PYTHONSTARTUP", "VIRTUAL_ENV", "PYTHONPATH", "PYTHONUSERBASE",
                   "PYTHONCASEOK", "PYTHONHASHSEED", "PYTHONOPTIMIZE", "PYTHONVERBOSE", "PYTHONDEBUG",
                   "PYTHONWARNINGS", "PYTHONIOENCODING", "PYTHONINSPECT"}


def runner_environment(inherited=None):
    source = os.environ if inherited is None else inherited
    result = {key.upper(): value for key, value in source.items() if key.upper() not in PYTHON_SETTINGS}
    if getattr(sys, 'frozen', False):
        bundled_settings = {'QT_PLUGIN_PATH', 'QT_QPA_PLATFORM_PLUGIN_PATH', 'QML2_IMPORT_PATH',
                            'QML_IMPORT_PATH', 'QT_QPA_FONTDIR', 'PYINSTALLER_RESET_ENVIRONMENT'}
        result = {key: value for key, value in result.items()
                  if key not in bundled_settings and not key.startswith('_PYI_')}
    system = result.get("SYSTEMROOT")
    if not system or not os.path.isabs(system):
        raise ValueError("absolute SystemRoot required")
    result["PATH"] = os.pathsep.join(str(Path(system) / part) for part in
                                  ("system32", "", "System32/Wbem", "System32/WindowsPowerShell/v1.0", "System32/OpenSSH"))
    result.update(PYTHONNOUSERSITE="1", PYTHONIOENCODING="utf-8", PYTHONUNBUFFERED="1")
    return result


def installation_manifest(root):
    """Hash executable/code/resource/config scope; do not copy secrets into reports."""
    root = Path(root).resolve()
    app = root / "data/apps/ok-ww"
    working = app / "working"
    roots = [working / part for part in ("src", "ok", "assets", "configs", "i18n", "ok_tasks", "ok_templates")]
    paths = [root / "ok-ww.exe", app / "app.json", app / ".pyappify-shortcut.py", working / "main.py", working / "config.py"]
    # Include bundled runtime/dependencies; ignore generated bytecode caches.
    roots.append(app / "python")
    for directory in roots:
        if directory.exists():
            paths.extend(path for path in directory.rglob("*")
                         if path.is_file() and "__pycache__" not in path.parts and path.suffix != ".pyc")
    files = {}
    for path in sorted(set(paths)):
        resolved = path.resolve(strict=True)
        if resolved != path.absolute() or not resolved.is_relative_to(root):
            raise ValueError("installation links or paths outside root require separate verification")
        digest = hashlib.sha256()
        with path.open("rb") as stream:
            before = os.fstat(stream.fileno())
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
            after = os.fstat(stream.fileno())
            if (before.st_size, before.st_mtime_ns, before.st_ino) != (after.st_size, after.st_mtime_ns, after.st_ino):
                raise ValueError("installation file changed while hashing")
        files[path.relative_to(root).as_posix()] = digest.hexdigest()
    content = json.dumps(files, sort_keys=True, separators=(",", ":")).encode()
    return {"scope": "ok-ww-working-and-runtime-v1", "files": files,
            "sha256": hashlib.sha256(content).hexdigest()}


def verify_manifest(root, expected):
    current = installation_manifest(root)
    if expected.get("scope") != current["scope"] or not isinstance(expected.get("files"), dict):
        return {"status": "changed", "reason": "manifest_schema_changed"}
    previous = expected["files"]
    changes = [path for path in sorted(set(previous) | set(current["files"]))
               if previous.get(path) != current["files"].get(path)]
    return {"status": "changed" if changes or expected.get("sha256") != current["sha256"] else "unchanged",
            "changed_files": changes, "current_sha256": current["sha256"]}


def prepare(root):
    manifest = installation_manifest(root)
    inventory = inspect_installation(root)
    game_config = Path(inventory["cwd"]) / "configs/devices.json"
    device = json.loads(game_config.read_text(encoding="utf-8")) if game_config.exists() else {}
    options_path = Path(inventory["cwd"]) / "configs/Basic Options.json"
    options = json.loads(options_path.read_text(encoding="utf-8")) if options_path.exists() else {}
    game_path = device.get("pc_full_path")
    privilege, desktop = elevation_report(), desktop_report()
    processes = find_matching_processes([inventory["runtime"], inventory["launcher"], game_path])
    blockers = ["daily_preset_not_authorized", "real_entry_not_verified", "game_job_inheritance_not_verified"]
    if inventory["code_version"] != "v3.6.7" or inventory["metadata_version"] != "v3.6.7":
        blockers.append("unsupported_or_mismatched_version")
    if inventory["task_index_observed"] is None:
        blockers.append("daily_task_binding_missing")
    if inventory["declared_admin_required"] is not True:
        blockers.append("admin_requirement_unknown")
    if privilege["elevated"] is not True:
        blockers.append("supervisor_elevation_required")
    if desktop["status"] != "observed_available":
        blockers.extend(desktop["blockers"])
    if processes["status"] != "observed" or processes["matches"]:
        blockers.append("existing_runner_or_game_not_exclusive")
    if not game_path or not Path(game_path).is_file():
        blockers.append("game_path_unverified")
    drift = verify_manifest(root, manifest)
    if drift["status"] != "unchanged":
        blockers.append("installation_changed_during_preparation")
    return {"schema_version": 1, "mode": "prepare_only", "game_execution": False, "status": "blocked",
            "argv_candidate": [inventory["runtime"], inventory["main_script"], "-t", "DailyTask", "-e"],
            "cwd": inventory["cwd"], "environment_policy": "pyappify-compatible-clean-python-v1",
            "installation_root": inventory["root"], "installation_manifest": manifest,
            "daily_preset": inventory["daily_preset"], "preset_sha256": next(
                f["sha256"] for f in inventory["files"] if Path(f["path"]).name == "DailyTask.json"),
            "game_path": game_path, "native_options": options, "privilege": privilege, "desktop": desktop,
            "existing_processes": processes, "blockers": blockers,
            "retries": 0, "runtime_fallback": False, "drift": drift}
